import enum
import uuid
from typing import TYPE_CHECKING, Any
from pgvector.sqlalchemy import Vector
from sqlalchemy import Boolean, Enum, ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.models.base import Base, TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.models.user import User
    from app.models.game import GameSession
    from app.models.bid import Bid, DraftedItem


class DeckCategory(str, enum.Enum):
    POP_CULTURE = "Pop Culture"
    CINEMA = "Cinéma"
    SERIES = "Séries"
    SPORT = "Sport"
    HISTOIRE = "Histoire"
    MANGAS = "Mangas"
    MUSIQUE = "Musique"
    GEOGRAPHIE = "Géographie"
    SCIENCES = "Sciences"
    AUTRE = "Autre"


class ItemRarity(str, enum.Enum):
    COMMON = "COMMON"        # Score 1-50
    UNCOMMON = "UNCOMMON"    # Valeur présente en base (0001_initial_schema)
    RARE = "RARE"            # Score 51-75
    EPIC = "EPIC"            # Score 76-90
    LEGENDARY = "LEGENDARY"  # Score 91-100


class Deck(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    __tablename__ = "decks"

    creator_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        index=True,
        nullable=True,
    )
    title: Mapped[str] = mapped_column(
        String(150),
        index=True,
        nullable=False,
    )
    slug: Mapped[str] = mapped_column(
        String(180),
        unique=True,
        index=True,
        nullable=False,
    )
    description: Mapped[str] = mapped_column(
        Text,
        default="",
        nullable=False,
    )
    category: Mapped[DeckCategory] = mapped_column(
        Enum(DeckCategory, name="deck_category_enum"),
        index=True,
        nullable=False,
    )
    tags: Mapped[list[str]] = mapped_column(
        JSONB,
        default=list,
        nullable=False,
    )
    is_public: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        index=True,
        nullable=False,
    )
    is_official: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        index=True,
        nullable=False,
    )
    play_count: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
    )
    likes_count: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
    )
    ai_prompt: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        doc="Original user prompt provided for Gemini generation",
    )

    # Relationships
    creator: Mapped["User | None"] = relationship(back_populates="decks")
    items: Mapped[list["DeckItem"]] = relationship(
        back_populates="deck",
        cascade="all, delete-orphan",
        order_by="DeckItem.base_score.desc()",
    )
    game_sessions: Mapped[list["GameSession"]] = relationship(back_populates="deck")


class DeckItem(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    __tablename__ = "deck_items"

    deck_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("decks.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    name: Mapped[str] = mapped_column(
        String(180),
        index=True,
        nullable=False,
        doc="Name of the item/character/movie/work",
    )
    clue_1: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Clue Level 1: Subtle, broad hints",
    )
    clue_2: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Clue Level 2: Intermediate context, notable facts",
    )
    clue_3: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Clue Level 3: Revealing, iconic elements",
    )
    base_score: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        doc="Base power/prestige score from 1 to 100 generated by Gemini",
    )
    rarity: Mapped[ItemRarity] = mapped_column(
        Enum(ItemRarity, name="item_rarity_enum"),
        nullable=False,
        doc="Computed rarity badge based on base_score",
    )
    category: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )
    embedding: Mapped[list[float] | None] = mapped_column(
        Vector(768),
        nullable=True,
        doc="Gemini 768-dim semantic embedding vector for synergy calculation and theme clustering",
    )
    metadata_json: Mapped[dict[str, Any] | None] = mapped_column(
        JSONB,
        default=dict,
        nullable=True,
        doc="Rich attributes: year, author, team, subgenre, etc.",
    )

    # Relationships
    deck: Mapped["Deck"] = relationship(back_populates="items")
    bids: Mapped[list["Bid"]] = relationship(back_populates="item")
    drafted_instances: Mapped[list["DraftedItem"]] = relationship(back_populates="item")
